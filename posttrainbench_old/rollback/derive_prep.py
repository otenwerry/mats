"""Auto-derive candidate prep_commands from a trajectory's trace (P4d).

23 of the 30 RH trajectories trained a model BEFORE the cut; the stripped archive
has no weights, so the cut-state workspace needs that model regenerated by
re-running the agent's pre-cut training pipeline (config.Trajectory.prep_commands).
Hand-writing those for 23 runs is the bottleneck — this derives CANDIDATES from
the trace.

Heuristic (exclude-based, robust to odd script names): scan pre-cut bash calls
for python-script invocations; KEEP the pipeline steps (training/data-prep/merge),
DROP eval/probe/analysis; dedup to the LAST run of each script (the agent's final
working version, after debugging re-runs); keep pipeline order; strip shell noise
(`cd .. &&`, `2>&1`, `| tee`, redirects).

!!! These are CANDIDATES, not ground truth. A wrong prep wastes a GPU run and/or
yields an unfaithful model. They MUST be validated on-box by the prep-smoke:
re-run the prep, score the regenerated model, and confirm it matches the recorded
pre-cut baseline (Trajectory.precut_eval_file) within stderr. Only then trust them.
Surfaced (not auto-applied) so Owen can eyeball/veto — curated prep_commands in
config.py always win.

    uv run python -m rollback.derive_prep                 # all needs-prep trajectories
    uv run python -m rollback.derive_prep <nick|run_id>   # one, verbose
"""
from __future__ import annotations

import json
import re
import sys

from . import config, ptbio

# A python EXECUTION segment: starts (after optional env-vars / timeout) with the
# interpreter, then the script. Anchored ^ so a .py mentioned inside grep/cat/echo
# string args does NOT match.
_EXEC = re.compile(r"^(?:\w+=\S+\s+)*(?:timeout\s+\S+\s+)?(?:python3?|accelerate|torchrun|uv\s+run(?:\s+python3?)?)\s+(?:-\S+\s+)*(\S+\.py)\b")


def _exec_segment(raw: str):
    """(script_basename, cleaned_command) for the python-execution segment of a
    bash command, or None if it isn't running a .py script."""
    # strip redirects FIRST (so '2>&1' isn't split apart), then split on
    # chain/pipe/background operators.
    c = re.sub(r"\s+\d*>>?\s*(?:&\d+|\S+)", "", raw.strip())   # 2>&1, >out, >>log
    for seg in re.split(r"\s*(?:&&|;|\||&(?!&)|\n)\s*", c):
        seg = seg.strip()
        # peel a leading `bash -lc '...'` wrapper (codex wraps commands this way)
        inner = re.sub(r"^(?:/bin/)?bash\s+-l?c\s+(['\"])(.*)\1$", r"\2", seg).strip()
        for cand in (seg, inner):
            m = _EXEC.match(cand)
            if m:
                return m.group(1).rsplit("/", 1)[-1], cand
    return None
# script-name substrings that mark a NON-pipeline call (eval/probe/analysis)
_EXCLUDE = re.compile(r"(eval|score|test|analy|inspect|baseline|check|probe|debug|verify|sanity)", re.I)
_PROBE = re.compile(r"(-m\s+py_compile|--help|\bpython3?\s+-c\b|pip\s+install|--dry[-_]?run)", re.I)
# pipeline STAGE by script name. 'train' is the expensive single-final-run stage
# (the model at the cut == the LAST training run), so we keep only its last
# command — collapsing competing versions like train.py vs train_v2.py. data-prep
# and merge can legitimately involve several distinct scripts, so there we keep
# the last run of EACH distinct script.
_PREP = re.compile(r"(prepare|preprocess|dataset|tokeniz|corpus|download|fetch|gather|_data|data_|build_|make_)", re.I)
_TRAIN = re.compile(r"(train|finetune|fine_tune|sft|lora|dpo|ppo|grpo|rlhf)", re.I)
_MERGE = re.compile(r"(merge|export|save_model)", re.I)


def _stage(script: str) -> str:
    # order matters: data-prep names like 'prepare_training_data' contain 'train',
    # so classify prep BEFORE train.
    if _MERGE.search(script):
        return "merge"
    if _PREP.search(script):
        return "prep"
    if _TRAIN.search(script):
        return "train"
    return "prep"   # anything else upstream of training


def _norm(script: str) -> str:
    """Collapse version-iterated names so e.g. prepare_data / prepare_data_v2 /
    prepare_data_fast count as ONE logical step (keep the last actual run)."""
    base = script[:-3] if script.endswith(".py") else script
    return re.sub(r"_(v?\d+|final|fast|new|fixed|clean|improved|simple|full)$", "",
                  base, flags=re.I)


def derive(traj: config.Trajectory, cut: int | None = None) -> list[dict]:
    """Ordered candidate prep steps: [{idx, script, command}]. Empty if none."""
    cut = traj.default_cut if cut is None else cut
    events = ptbio.load_events(traj)
    # keyed kept commands. prep/merge: key by (stage, script) — distinct scripts
    # kept, re-runs collapsed. train: key by "train" alone — only the last training
    # survives (competing train scripts collapse to the final one).
    kept: dict[str, dict] = {}
    for tc in ptbio.iter_tool_calls(events, cut):
        if tc.name.lower() != "bash":
            continue
        raw = tc.input.get("command", "") or ""
        if _PROBE.search(raw):
            continue
        seg = _exec_segment(raw)
        if not seg:
            continue
        script, command = seg
        if _EXCLUDE.search(script):
            continue
        stage = _stage(script)
        # train collapses to ONE final run; prep/merge collapse version-iterated
        # scripts (prepare_data vs prepare_data_v2) but keep genuinely-distinct ones.
        key = "train" if stage == "train" else f"{stage}:{_norm(script)}"
        kept[key] = {"idx": tc.idx, "script": script, "command": command, "stage": stage}
    return sorted(kept.values(), key=lambda r: r["idx"])


def candidate_commands(traj: config.Trajectory, cut: int | None = None) -> list[str]:
    return [r["command"] for r in derive(traj, cut)]


def reliability(steps: list[dict]) -> str:
    """Rough confidence in the derived pipeline. 'clean' = a single canonical
    train run with prep before / merge after it and few steps (auto-derivation
    is trustworthy, pending prep-smoke). 'review' = interleaved order, no detected
    training, or many steps — needs a human look before a real prep run."""
    if not steps:
        return "review (no training pipeline detected)"
    stages = [s["stage"] for s in steps]
    if stages.count("train") != 1:
        return "review (not exactly one training step)"
    ti = stages.index("train")
    if any(st == "prep" for st in stages[ti + 1:]) or any(st == "merge" for st in stages[:ti]):
        return "review (prep/merge out of order vs train — agent interleaved)"
    if len(steps) > 4:
        return f"review ({len(steps)} steps — complex pipeline)"
    return "clean"


def main() -> None:
    if len(sys.argv) > 1:
        traj = config.get_trajectory(sys.argv[1])
        steps = derive(traj)
        print(f"{traj.run_id}  cut={traj.default_cut}  needs_prep={traj.needs_prep}")
        print(f"  curated prep_commands: {list(traj.prep_commands) or '(none)'}")
        print(f"  DERIVED candidate prep ({len(steps)} step(s)):")
        for s in steps:
            print(f"    ev{s['idx']:>4}  {s['command']}")
        return
    # all needs-prep trajectories: derived candidates + agreement w/ curated
    n_ok = n_total = 0
    for rid, traj in config.ALL_TRAJECTORIES.items():
        if not traj.needs_prep:
            continue
        n_total += 1
        derived = candidate_commands(traj)
        curated = list(traj.prep_commands)
        flag = ""
        if curated:
            match = derived == curated
            n_ok += match
            flag = "  <= MATCHES curated" if match else "  <= DIFFERS from curated"
        rel = reliability(derive(traj))
        print(f"\n[{rel.split()[0].upper():6}] {traj.scaffold:8} cut={traj.default_cut:>4} {rid[:50]}{flag}")
        if rel != "clean":
            print(f"    ! {rel}")
        for cmd in derived:
            print(f"    {cmd}")
    clean = sum(reliability(derive(t)) == "clean" for t in config.ALL_TRAJECTORIES.values() if t.needs_prep)
    print(f"\n{n_total} needs-prep trajectories: {clean} derived 'clean', "
          f"{n_total - clean} need review. Of those with curated prep, {n_ok}/2 reproduced "
          f"exactly. ALL candidates pending on-box prep-smoke validation (regenerated "
          f"model must score ~ the recorded pre-cut baseline).")


if __name__ == "__main__":
    main()
